//! The 105 CUDA Tile opcodes, with the names they print as.
//!
//! Ported verbatim from `cutile-ir`'s `bytecode/opcode.rs`. The discriminant of
//! each variant is its on-wire opcode value: those numbers are frozen for
//! compatibility, so a variant added here must never be renumbered.

/// One CUDA Tile operation code.
